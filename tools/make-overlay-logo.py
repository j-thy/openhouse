#!/usr/bin/env python3
"""Rasterizes the logo SVG into apps/openhouse-overlay/logo_rgba.h (embedded RGBA pixels).

The overlay shows the logo in its sidebar and as SteamVR's dashboard button; it has no
image decoder, so the pixels are baked in. Rerun after replacing the SVG:

    tools/make-overlay-logo.py [LOGO.svg]      (needs rsvg-convert and ImageMagick)

The drawing is cropped to what's painted and padded to a square.
"""
import os, subprocess, sys, tempfile
repo = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
svg = sys.argv[1] if len(sys.argv) > 1 else os.path.join(repo, 'tools', 'horrible-logo-to-be-replaced.svg')
size = 256
out = os.path.join(repo, 'apps', 'openhouse-overlay', 'logo_rgba.h')
with tempfile.TemporaryDirectory() as tmp:
    png = os.path.join(tmp, 'logo.png')
    subprocess.run(['rsvg-convert', '-w', '1904', '-o', png, svg], check=True)
    rgba = subprocess.run(['magick', png, '-trim', '+repage', '-background', 'none', '-gravity', 'center',
                           '-resize', f'{size - 8}x{size - 8}', '-extent', f'{size}x{size}', '-depth', '8', 'rgba:-'],
                          check=True, capture_output=True).stdout
assert len(rgba) == size * size * 4, len(rgba)
with open(out, 'w') as f:
    f.write('// Generated by tools/make-overlay-logo.py from %s: do not edit.\n' % os.path.basename(svg))
    f.write('#pragma once\n#include <cstdint>\n\nnamespace openhouse::overlay {\n')
    f.write(f'constexpr int kLogoSize = {size};\n')
    f.write('inline const uint8_t kLogoRgba[] = {\n')
    for i in range(0, len(rgba), 32):
        f.write('  ' + ','.join(str(b) for b in rgba[i:i + 32]) + ',\n')
    f.write('};\n}  // namespace openhouse::overlay\n')
print(out)
