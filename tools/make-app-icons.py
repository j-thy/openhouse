#!/usr/bin/env python3
"""App icons from the logo SVG: the Windows .ico files the executables carry and the Doorman
Dongle Manager's window icon (the logo with a wireless USB dongle badge).

    tools/make-app-icons.py [LOGO.svg]      (needs rsvg-convert, ImageMagick and Pillow)

Writes cmake/windows/openhouse.ico (overlay, installer), cmake/windows/dongle-manager.ico and
apps/doorman-dongle-manager/dongle_logo_rgba.h. tools/make-overlay-logo.py makes the plain
logo's pixels for the overlay and the installer windows.
"""
import io, os, subprocess, sys, tempfile
from PIL import Image, ImageDraw

repo = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
svg = sys.argv[1] if len(sys.argv) > 1 else os.path.join(repo, 'tools', 'horrible-logo-to-be-replaced.svg')
with tempfile.TemporaryDirectory() as tmp:
    png = os.path.join(tmp, 'logo.png')
    subprocess.run(['rsvg-convert', '-w', '1904', '-o', png, svg], check=True)
    data = subprocess.run(['magick', png, '-trim', '+repage', '-background', 'none', '-gravity', 'center',
                           '-resize', '1016x1016', '-extent', '1024x1024', 'png:-'], check=True, capture_output=True).stdout
logo = Image.open(io.BytesIO(data)).convert('RGBA')


def badge(img):
    """A wireless USB dongle on a blue disc, bottom right (drawn at 1024 px)."""
    out = img.copy()
    d = ImageDraw.Draw(out)
    cx, cy, r = 760, 760, 250
    d.ellipse((cx - r - 24, cy - r - 24, cx + r + 24, cy + r + 24), fill=(17, 19, 25, 255))  # gap to the logo
    d.ellipse((cx - r, cy - r, cx + r, cy + r), fill=(64, 120, 220, 255))
    white = (255, 255, 255, 255)
    # The dongle, tilted up: connector at the top, body below.
    stick = Image.new('RGBA', (1024, 1024), (0, 0, 0, 0))
    s = ImageDraw.Draw(stick)
    bx, by = cx - 20, cy + 40
    s.rectangle((bx - 46, by - 190, bx + 46, by - 100), outline=white, width=22)          # connector
    s.rectangle((bx - 26, by - 165, bx - 8, by - 140), fill=white)                       # its contacts
    s.rectangle((bx + 8, by - 165, bx + 26, by - 140), fill=white)
    s.rounded_rectangle((bx - 70, by - 100, bx + 70, by + 150), radius=36, fill=white)   # body
    out.alpha_composite(stick)
    # Radio waves beside the connector.
    for k, (rr, w) in enumerate(((70, 24), (125, 24))):
        ax, ay = bx + 70, by - 120
        d.arc((ax - rr, ay - rr, ax + rr, ay + rr), start=-80, end=-10, fill=white, width=w)
    return out


def write_ico(img, path):
    sizes = [16, 24, 32, 48, 64, 128, 256]
    img.resize((256, 256), Image.LANCZOS).save(path, format='ICO', sizes=[(n, n) for n in sizes])
    print(path)


dongle = badge(logo)
write_ico(logo, os.path.join(repo, 'cmake', 'windows', 'openhouse.ico'))
write_ico(dongle, os.path.join(repo, 'cmake', 'windows', 'dongle-manager.ico'))
rgba = dongle.resize((256, 256), Image.LANCZOS).tobytes()
out = os.path.join(repo, 'apps', 'doorman-dongle-manager', 'dongle_logo_rgba.h')
with open(out, 'w') as f:
    f.write('// Generated by tools/make-app-icons.py from %s: do not edit.\n' % os.path.basename(svg))
    f.write('#pragma once\n#include <cstdint>\n\nnamespace openhouse::dongle {\n')
    f.write('constexpr int kDongleLogoSize = 256;\n')
    f.write('inline const uint8_t kDongleLogoRgba[] = {\n')
    for i in range(0, len(rgba), 32):
        f.write('  ' + ','.join(str(b) for b in rgba[i:i + 32]) + ',\n')
    f.write('};\n}  // namespace openhouse::dongle\n')
print(out)
